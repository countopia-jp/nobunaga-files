export const RUBRIC = {
  5: { label: '確実',   short: '同時代の一次史料で裏付け（書状・当事者の日記など）' },
  4: { label: '有力',   short: '一次に近い良質な編纂物（『信長公記』など）' },
  3: { label: '諸説',   short: '複数の後代編纂物で一致するが一次では未確認' },
  2: { label: '疑わし', short: '軍記物が主な典拠（後世の脚色）' },
  1: { label: '創作',   short: '講談・近代の創作・ドラマ発。史料に根拠なし' },
};

// 出典の種別。信憑性度と同じ「史料の近さ」の物差しで色分けする。
