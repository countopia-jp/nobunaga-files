// 信憑性度の採点基準（5段階）。
// 測るのは「真偽」ではなく《その通説を支える史料の近さ・強さ》。
//
// 最上位を「確実」ではなく「裏づけ」としているのは、
// この段階が保証するのは「同時代の記録がそう書いている」ことまでで、
// 事実であることまでは保証しないため。一次史料も、
// 相手を動かすために書かれ、伝聞を含む。
// 判定の語ではなく状態の語を置くことで、読者を出典欄へ向かわせる。
//
// 同じ理由で、最下位も「創作」から「典拠なし」に改めた（2026-08-25）。
// 初出が後代であることと、後代に作られたことは別である。語りとして
// 伝わってから文字になった経路は排除できず、「見つからない」を
// 「作られた」と言い換えるのは、このサイトが他所で繰り返し書いている
// 「ないことは証明にならない」と矛盾する。★2の「疑わし」も真偽の語
// だったため、典拠の種類を示す「軍記」に替えた。
//
// なお出典の種別ラベルとしての「創作」は残している。こちらは
// 『絵本太閤記』や近代の小説そのものを指すので、その資料が創作物で
// あることは事実であり、通説を創作と呼ぶのとは別の話になる。

export const RUBRIC = {
  5: { label: '裏付',   short: '同時代の一次史料に裏づけがある（書状・当事者の日記など）' },
  4: { label: '有力',   short: '一次に近い良質な編纂物（『信長公記』など）' },
  3: { label: '諸説',   short: '複数の後代編纂物で一致するが一次では未確認' },
  2: { label: '軍記',   short: '軍記物が主な典拠。読み物として書かれたもので、支えとしては遠い' },
  1: { label: '典拠なし', short: '支える史料が見つからない。文字に残らなかっただけの可能性も含む' },
};

// 「一次史料」を一つにまとめると、当事者が自分で発した文書と、
// 京や奈良で噂を聞き書きした日記が、同じ重さに見えてしまう。
// どちらも同時代の記録だが、書き手と出来事の距離が違う。
// ランクは分けない（日記が格下という話ではない）。種別を分けて、
// 当事者の手によるものか、同時代人が書き留めたものかを示す。
// なお日記の中でも、見たことと聞いたことは条によって混ざる。
// そこは個別の注で書く。
export const SOURCE_KIND = {
  '一次': { rank: 5, note: '当事者が発した文書（書状・朱印状・禁制・起請文など）' },
  '同時代': { rank: 5, note: '同時代人が書き留めた記録（公家・僧侶の日記、茶会記など）。書き手が見たのか聞いたのかは条による' },
  '編纂': { rank: 4, note: '一次に近い編纂物（当事者・側近の記録）' },
  '後代': { rank: 3, note: '後代の編纂物・地誌' },
  '軍記': { rank: 2, note: '軍記物語（後世の読み物・脚色を含む）' },
  '創作': { rank: 1, note: '講談・近代の創作・ドラマ' },
};

export function rubricOf(rating) {
  return RUBRIC[rating] ?? RUBRIC[3];
}
