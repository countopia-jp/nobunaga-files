/* 公開の可否
   ---------------------------------------------
   verified: true のエピソードだけを公開する。false のものは
   トップでは封をしたカードとして暗く表示し、詳細ページ自体を生成しない。
   人力の検証が済んだものから、この値を true に変えて開けていく。 */
export function isOpen(slug) {
  const e = episodes.find((x) => x.slug === slug);
  return !!(e && e.verified);
}

// href が未公開の検証ファイルを指していないか。データ側に直接書かれた
// リンク（link.href / related / core.href など）の出し分けに使う。
export function hrefOpen(href) {
  if (typeof href !== 'string') return true;
  const m = href.match(/^\/episodes\/([a-z0-9-]+)\/?$/);
  if (!m) return true;
  return isOpen(m[1]);
}

export function openCount() {
  return { open: episodes.filter((e) => e.verified).length, all: episodes.length };
}

// 年に紐づくエピソードを古い順に。トップの年表はこれを使う。
export function episodesByYear() {
  return episodes.filter((e) => e.year != null).sort((a, b) => a.year - b.year);
}

// 特定の年に紐づかない「人物像」エピソード。
export function timelessEpisodes() {
  return episodes.filter((e) => e.year == null);
}

export function getEpisode(slug) {
  return episodes.find((e) => e.slug === slug);
}

// エピソード内の信憑性度の幅（最小〜最大）。
export function ratingRange(ep) {
  const rs = ep.points.map((p) => p.rating);
  return { min: Math.min(...rs), max: Math.max(...rs) };
}
