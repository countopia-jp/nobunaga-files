export function enemyStats() {
  const all = enemies.flatMap((g) => g.forces);
  return {
    groups: enemies.length,
    forces: all.length,
    destroyed: all.filter((f) => f.outcome === '滅亡' || f.outcome === '離反のち滅亡').length,
    unresolved: all.filter((f) => f.outcome === '決着せず').length,
  };
}
