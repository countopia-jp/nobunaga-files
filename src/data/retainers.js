export function retainerStats() {
  const all = retainers.flatMap((g) => g.people);
  const byFate = {};
  for (const p of all) byFate[p.fate] = (byFate[p.fate] ?? 0) + 1;
  return {
    groups: retainers.length,
    people: all.length,
    myths: all.filter((p) => p.myth).length,
    byFate,
  };
}
